"""Generate the two star icons of the HOST layout picker (ADR-039 section 3).

The picker needs one control with two states that cannot be mistaken for each other or for the check mark that
marks the layout in force: a solid star on a pinned row, a hollow one on a row that is not pinned. Neither the
theme's Montserrat set nor the Noto Sans subset of TECH-078 has a star (U+2605 / U+2606 live in Noto Sans
Symbols2, a font this project does not ship), so the two shapes are drawn here instead of borrowed: a five-point
star is a closed polygon, and a few lines of arithmetic cost less than another font, another download and
another license row.

The output is one C file with two ``lv_image_dsc_t`` of format ``LV_COLOR_FORMAT_A8`` - alpha only, so the view
colors each one through ``image_recolor`` and no palette is baked into the image. Rasterization is a 4x4
supersampled even-odd fill, which is what gives the edges their gray steps; the same input always produces the
same bytes, so the file is reproducible.

Usage (run from the repository root; nothing is written outside --out):
    python -I tools/fonts/gen_star_icon.py --out components/ui_theme/src/ui_icon_star.c
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path

SIZE = 24          # px, the side of both icons: one UI_TOUCH_MIN button holds it with room to spare
SAMPLES = 4        # supersampling per axis
OUTER = 11.2       # outer radius, in pixels, leaving a hairline of margin inside SIZE
INNER_RATIO = 0.42 # the waist of a five-point star
STROKE = 2.2       # the ring width of the hollow star

HEADER = """// SPDX-License-Identifier: PolyForm-Noncommercial-1.0.0
// Copyright 2026 D-Ogi. Noncommercial use only; see LICENSE.md.
// Required Notice: Copyright 2026 D-Ogi (https://github.com/D-Ogi/esp32-s3-kvmpad)
//
// Generated by tools/fonts/gen_star_icon.py - do not edit by hand.
// The pinned / not pinned star of the HOST layout picker (ADR-039 section 3), alpha only: the view gives each
// one its color through the image_recolor style, so the icons follow the theme instead of fixing it.
"""


def star_points(scale: float) -> list[tuple[float, float]]:
    """The ten corners of a five-point star of radius `OUTER * scale`, point up, around the icon's center."""
    mid = SIZE / 2.0
    pts: list[tuple[float, float]] = []
    for i in range(10):
        radius = OUTER * scale * (1.0 if i % 2 == 0 else INNER_RATIO)
        angle = -math.pi / 2.0 + i * math.pi / 5.0
        pts.append((mid + radius * math.cos(angle), mid + radius * math.sin(angle)))
    return pts


def inside(poly: list[tuple[float, float]], x: float, y: float) -> bool:
    """Even-odd test: a ray to the right crosses an odd number of edges exactly inside the polygon."""
    hit = False
    for i in range(len(poly)):
        x1, y1 = poly[i]
        x2, y2 = poly[(i + 1) % len(poly)]
        if (y1 > y) != (y2 > y):
            cross = x1 + (y - y1) * (x2 - x1) / (y2 - y1)
            if x < cross:
                hit = not hit
    return hit


def raster(outer: list[tuple[float, float]], hole: list[tuple[float, float]] | None) -> bytes:
    """One A8 plane: the coverage of `outer` minus `hole`, supersampled SAMPLES x SAMPLES per pixel."""
    out = bytearray(SIZE * SIZE)
    step = 1.0 / SAMPLES
    for py in range(SIZE):
        for px in range(SIZE):
            covered = 0
            for sy in range(SAMPLES):
                for sx in range(SAMPLES):
                    x = px + (sx + 0.5) * step
                    y = py + (sy + 0.5) * step
                    if inside(outer, x, y) and not (hole is not None and inside(hole, x, y)):
                        covered += 1
            out[py * SIZE + px] = round(covered * 255 / (SAMPLES * SAMPLES))
    return bytes(out)


def emit(name: str, data: bytes) -> str:
    rows = []
    for i in range(0, len(data), 12):
        rows.append("    " + " ".join(f"0x{b:02X}," for b in data[i:i + 12]))
    body = "\n".join(rows)
    return (
        f"static const uint8_t {name}_map[{len(data)}] = {{\n{body}\n}};\n\n"
        f"const lv_image_dsc_t {name} = {{\n"
        "    .header = {\n"
        "        .magic = LV_IMAGE_HEADER_MAGIC,\n"
        "        .cf = LV_COLOR_FORMAT_A8,\n"
        "        .flags = 0,\n"
        f"        .w = {SIZE},\n"
        f"        .h = {SIZE},\n"
        f"        .stride = {SIZE},\n"
        "        .reserved_2 = 0,\n"
        "    },\n"
        f"    .data_size = sizeof({name}_map),\n"
        f"    .data = {name}_map,\n"
        "    .reserved = NULL,\n"
        "};\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", required=True, help="the C file to write")
    args = ap.parse_args()

    full = star_points(1.0)
    # The hollow star is the same outline with a smaller one taken out of it, so both read as the same shape.
    hole_scale = max(0.0, (OUTER - STROKE) / OUTER)
    hollow_hole = star_points(hole_scale)

    text = HEADER + '\n#include "ui_icon_star.h"\n\n'
    text += emit("ui_icon_star_filled", raster(full, None))
    text += "\n"
    text += emit("ui_icon_star_hollow", raster(full, hollow_hole))

    out = Path(args.out)
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"{out}: two {SIZE}x{SIZE} A8 icons, {SIZE * SIZE} bytes each")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
