"""Export a transparent four-by-four control atlas to Windows PNG and LVGL 9 A4.

python design/assets/export_control_icons.py --atlas controls.png
Omit --atlas to rebuild the LCD resource from the checked-in Windows masks.
"""
import argparse
from itertools import groupby
from pathlib import Path

from PIL import Image, ImageOps


NAMES = (
    "mouse", "keyboard", "shortcuts", "extensions",
    "host", "client", "connect", "disconnect",
    "magnifier", "video", "card", "settings",
    "day", "night", "contrast", "home",
)
ASSETS = Path(__file__).resolve().parent
COMPONENT = ASSETS.parents[1] / "components" / "ui_theme"
PNG_DIR = ASSETS / "control-icons"
NOTICE = """// SPDX-License-Identifier: PolyForm-Noncommercial-1.0.0
// Copyright 2026 D-Ogi. Noncommercial use only; see LICENSE.md.
// Required Notice: Copyright 2026 D-Ogi (https://github.com/D-Ogi/esp32-s3-kvmpad)
// Generated by design/assets/export_control_icons.py.
"""


def separators(projection):
    """Cut through empty gutters even when the original grid is off-center."""
    extent = len(projection)
    gutters = []
    for ink, indices in groupby(range(extent), key=projection.__getitem__):
        if not ink:
            run = list(indices)
            if len(run) >= 3 and run[0] > 0 and run[-1] < extent - 1:
                gutters.append((run[0] + run[-1] + 1) // 2)
    cuts = [0]
    for quarter in (1, 2, 3):
        target = quarter * extent / 4
        candidates = [middle for middle in gutters if abs(middle - target) <= extent / 12]
        if not candidates:
            raise ValueError(f"No transparent gutter near {target:g} of {extent} pixels")
        cuts.append(min(candidates, key=lambda middle: abs(middle - target)))
    return [*cuts, extent]


def masks_from_atlas(path):
    with Image.open(path) as atlas:
        if atlas.mode != "RGBA":
            raise ValueError("The control atlas needs an RGBA transparency channel")
        # The artwork has a faint matte at both extremes. Keep antialiasing
        # between those extremes and give the transparent gutters a true zero.
        alpha = atlas.getchannel("A").point(
            [max(0, min(255, ((value - 12) * 255 + 115) // 231)) for value in range(256)]
        )
    xs, ys = map(separators, alpha.getprojection())
    masks = {}
    for index, name in enumerate(NAMES):
        row, col = divmod(index, 4)
        tile = alpha.crop((xs[col], ys[row], xs[col + 1], ys[row + 1]))
        bounds = tile.getbbox()
        if not bounds or not (0 < bounds[0] < bounds[2] < tile.width and
                              0 < bounds[1] < bounds[3] < tile.height):
            raise ValueError(f"Empty or clipped source artwork for {name}")
        glyph = ImageOps.contain(tile.crop(bounds), (80, 80), Image.Resampling.LANCZOS)
        canvas = Image.new("L", (96, 96))
        canvas.paste(glyph, ((96 - glyph.width) // 2, (96 - glyph.height) // 2))
        masks[name] = canvas
    return masks


def write_pngs(masks):
    PNG_DIR.mkdir(exist_ok=True)
    for name, mask in masks.items():
        image = Image.new("RGBA", mask.size, "white")
        image.putalpha(mask)
        image.save(PNG_DIR / f"{name}.png", compress_level=9, optimize=False)


def read_pngs():
    masks = {}
    for name in NAMES:
        with Image.open(PNG_DIR / f"{name}.png") as image:
            if image.mode != "RGBA" or image.size != (96, 96) or image.getextrema()[:3] != ((255, 255),) * 3:
                raise ValueError(f"Invalid white 96x96 RGBA mask for {name}")
            masks[name] = image.getchannel("A")
    return masks


def pack_a4(mask):
    sampled = mask.resize((24, 24), Image.Resampling.LANCZOS)
    coverage = sampled.point([(value + 8) // 17 for value in range(256)]).tobytes()
    # LVGL stores the left pixel in the high four bits of each byte.
    return bytes(left << 4 | right for left, right in zip(coverage[::2], coverage[1::2]))


def write_lcd(masks):
    header = [NOTICE, '#pragma once\n\n#include "lvgl.h"\n',
              '#ifdef __cplusplus\nextern "C" {\n#endif\n']
    source = [NOTICE, '#include "kvm_control_icons.h"\n']
    for name, mask in masks.items():
        symbol = f"kvm_icon_{name}"
        packed = pack_a4(mask)
        header.append(f"LV_IMAGE_DECLARE({symbol});")
        source.append(f"static const uint8_t {symbol}_map[] = {{")
        for start in range(0, len(packed), 12):
            source.append("    " + ", ".join(f"0x{v:02x}" for v in packed[start:start + 12]) + ",")
        source.extend([
            "};", "",
            f"const lv_image_dsc_t {symbol} = {{",
            "    .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A4,",
            "                .w = 24, .h = 24, .stride = 12 },",
            f"    .data_size = sizeof({symbol}_map),",
            f"    .data = {symbol}_map,",
            "};", "",
        ])
    header.extend(["", "#ifdef __cplusplus", "}", "#endif", ""])
    (COMPONENT / "include/kvm_control_icons.h").write_text("\n".join(header), encoding="ascii", newline="\n")
    (COMPONENT / "src/kvm_control_icons.c").write_text("\n".join(source), encoding="ascii", newline="\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--atlas", type=Path, help="Update the PNG masks from the supplied 4x4 RGBA master")
    args = parser.parse_args()
    if args.atlas:
        write_pngs(masks_from_atlas(args.atlas))
    write_lcd(read_pngs())
