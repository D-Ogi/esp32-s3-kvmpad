/* Scores of the Java original. */
#define FREQ_LEARN 600
#define CLAUSE_COST (-1000)
/* Longest clause the consecutive search tries, as in consecutiveClauseConvert(). */
#define MAX_CLAUSE_KANA 20
/* Engine dictionary indices the clause conversion uses (setDictionary() of the original). */
#define DIC_TANKANJI 4
#define DIC_JIRITSU 5
#define DIC_FZK 6
#define DIC_FIRST DIC_TANKANJI
#define DIC_COUNT 3

typedef struct {
    uint16_t off;
    uint8_t cnt;
    uint8_t valid;
} wnn_list_t;

struct wnn_conv {
    /* The engine's own state, as NJ_JNIWORK of the JNI original. */
    NJ_CLASS wnn;
    NJ_CURSOR cursor;
    NJ_DIC_SET dicset;
    NJ_RESULT result;
    NJ_CHARSET approx; /* always empty: no approximate patterns */
    NJ_SEARCH_CACHE cache[DIC_COUNT];
    NJ_CHAR key[NJ_MAX_LEN + NJ_TERM_LEN];
    NJ_DIC_HANDLE handle[DIC_COUNT];
    NJ_UINT16 lcount, rcount;

    /* Part-of-speech tags, as getPOS() of the original. */
    uint16_t pos_def_l, pos_def_r;
    uint16_t pos_eoc1_l, pos_eoc2_l, pos_eoc3_l;

    /* The reading being converted. */
    NJ_CHAR kana[WNN_MAX_KANA + NJ_TERM_LEN];
    uint8_t kana_len;
    uint8_t cur_start, cur_len; /* range of the search in flight */
    uint8_t dic_mode;           /* 0 none, 1 independent words, 2 ancillary words */

    /* Word and text arenas. str[0..WNN_MAX_KANA) always holds the reading, so a word whose text is
     * its own reading needs no arena space. */
    wnn_word_t words[WNN_MAX_WORDS];
    uint16_t word_n;
    uint16_t str[WNN_STR_UNITS];
    uint16_t str_n;
    bool truncated;

    wnn_list_t indep[WNN_MAX_KANA + 1][WNN_MAX_KANA + 1];
    wnn_list_t fzk[WNN_MAX_KANA + 1][WNN_MAX_KANA + 1];
    wnn_word_t stems[WNN_MAX_LIST];

    struct {
        bool set;
        int32_t freq;
        uint8_t start;
        wnn_word_t clause;
    } dp[WNN_MAX_KANA];
};

/* --- NJ_CHAR is a UTF-16 code unit stored big endian, whatever the host is (nj_ext.h). --- */

static void nj_put(NJ_CHAR *dst, uint16_t u)
{
    ((NJ_UINT8 *)dst)[0] = (NJ_UINT8)(u >> 8);
    ((NJ_UINT8 *)dst)[1] = (NJ_UINT8)(u & 0xffu);
}

static uint16_t nj_get(const NJ_CHAR *src)
{
    const NJ_UINT8 *b = (const NJ_UINT8 *)src;
    return (uint16_t)(((uint16_t)b[0] << 8) | b[1]);
}

/* --- dictionary set, as clearDictionaryParameters() / setDictionaryParameter() of the JNI --- */

static void clear_dics(wnn_conv_t *c)
{
    for (int i = 0; i < NJ_MAX_DIC; i++) {
        c->dicset.dic[i].type = 0;
        c->dicset.dic[i].handle = NULL;
        c->dicset.dic[i].dic_freq[NJ_MODE_TYPE_HENKAN].base = 0;
        c->dicset.dic[i].dic_freq[NJ_MODE_TYPE_HENKAN].high = 0;
    }
    memset(c->dicset.keyword, 0, sizeof(c->dicset.keyword));
}

static void set_dic(wnn_conv_t *c, int index, uint16_t base, uint16_t high)
{
    c->dicset.dic[index].type = NJ_DIC_H_TYPE_NORMAL;
    c->dicset.dic[index].handle = c->handle[index - DIC_FIRST];
    c->dicset.dic[index].srhCache = &c->cache[index - DIC_FIRST];
    c->dicset.dic[index].dic_freq[NJ_MODE_TYPE_HENKAN].base = base;
    c->dicset.dic[index].dic_freq[NJ_MODE_TYPE_HENKAN].high = high;
}

static void dics_for_indep(wnn_conv_t *c)
{
    if (c->dic_mode == 1) {
        return;
    }
    clear_dics(c);
    set_dic(c, DIC_TANKANJI, 0, 10);
    set_dic(c, DIC_JIRITSU, 400, 500);
    c->dic_mode = 1;
}

static void dics_for_fzk(wnn_conv_t *c)
{
    if (c->dic_mode == 2) {
        return;
    }
    clear_dics(c);
    set_dic(c, DIC_FZK, 400, 500);
    c->dic_mode = 2;
}

/* --- searching, as searchWord() / getNextWord() of the JNI --- */

static bool search_range(wnn_conv_t *c, NJ_UINT8 operation, size_t start, size_t end)
{
    if (end <= start || end > c->kana_len || end - start > NJ_MAX_LEN) {
        return false;
    }
    for (size_t i = start; i < end; i++) {
        c->key[i - start] = c->kana[i];
    }
    c->key[end - start] = NJ_CHAR_NUL;
    c->cur_start = (uint8_t)start;
    c->cur_len = (uint8_t)(end - start);

    memset(&c->result, 0, sizeof(c->result));
    memset(&c->cursor, 0, sizeof(c->cursor));
    c->cursor.cond.operation = operation;
    c->cursor.cond.mode = NJ_CUR_MODE_FREQ;
    c->cursor.cond.ds = &c->dicset;
    c->cursor.cond.yomi = c->key;
    c->cursor.cond.charset = &c->approx;
    memcpy(&c->wnn.dic_set, &c->dicset, sizeof(NJ_DIC_SET));
    return njx_search_word(&c->wnn, &c->cursor) == 1;
}

static bool alloc_text(wnn_conv_t *c, const NJ_CHAR *s, size_t n, uint16_t *off, uint8_t *len)
{
    if (n == 0 || n > WNN_MAX_RESULT) {
        return false;
    }
    if (c->str_n + n > WNN_STR_UNITS) {
        c->truncated = true;
        return false;
    }
    *off = c->str_n;
    for (size_t i = 0; i < n; i++) {
        c->str[c->str_n++] = nj_get(&s[i]);
    }
    *len = (uint8_t)n;
    return true;
}

/** Next word of the search in flight. `stroke_eq` tells whether its reading is the search key. */
static bool next_word(wnn_conv_t *c, wnn_word_t *out, bool *stroke_eq)
{
    NJ_CHAR stroke[NJ_MAX_LEN + NJ_TERM_LEN];
    NJ_CHAR cand[NJ_MAX_RESULT_LEN + NJ_TERM_LEN];

    while (njx_get_word(&c->wnn, &c->cursor, &c->result) > 0) {
        const NJ_INT16 slen = njx_get_stroke(&c->wnn, &c->result, stroke, sizeof(stroke));
        const NJ_INT16 clen = njx_get_candidate(&c->wnn, &c->result, cand, sizeof(cand));
        if (slen < 0 || clen <= 0) {
            continue; /* unreadable word: skip it and go on */
        }
        memset(out, 0, sizeof(*out));
        if (!alloc_text(c, cand, (size_t)clen, &out->cand_off, &out->cand_len)) {
            return false;
        }
        out->stroke_start = c->cur_start;
        out->stroke_len = c->cur_len;
        out->freq = c->result.word.stem.hindo;
        out->pos_left = NJ_GET_FPOS_FROM_STEM(&c->result.word);
        out->pos_right = NJ_GET_BPOS_FROM_STEM(&c->result.word);

        *stroke_eq = (size_t)slen == (size_t)c->cur_len;
        for (size_t i = 0; *stroke_eq && i < (size_t)slen; i++) {
            if (nj_get(&stroke[i]) != nj_get(&c->kana[c->cur_start + i])) {
                *stroke_eq = false;
            }
        }
        return true;
    }
    return false;
}

/* --- connectible(), as getConnectMatrix() of the original read through njd_r_get_connect() --- */

static bool connectible(wnn_conv_t *c, uint16_t right, uint16_t left)
{
    if (left < 1 || left > c->lcount || right < 1 || right > c->rcount) {
        return false; /* the original catches the out-of-range access and answers false */
    }
    NJ_UINT8 *conn = NULL;
    if (njd_r_get_connect(c->dicset.rHandle[NJ_MODE_TYPE_HENKAN], left, NJ_RULE_TYPE_FTOB, &conn) < 0 ||
        conn == NULL) {
        return false;
    }
    const size_t i = (size_t)right - 1u;
    return (conn[i / 8] & (0x80u >> (i % 8))) != 0;
}

/* --- word lists --- */

static bool push_word(wnn_conv_t *c, const wnn_word_t *w, uint8_t *n)
{
    if (*n >= WNN_MAX_LIST || c->word_n >= WNN_MAX_WORDS) {
        c->truncated = true;
        return false;
    }
    c->words[c->word_n++] = *w;
    (*n)++;
    return true;
}

/** A word whose text is its own reading, as addAutoGeneratedCandidates() / defaultClause(). */
static wnn_word_t plain_word(const wnn_conv_t *c, size_t start, size_t len)
{
    wnn_word_t w;
    memset(&w, 0, sizeof(w));
    w.cand_off = (uint16_t)start;
    w.cand_len = (uint8_t)len;
    w.stroke_start = (uint8_t)start;
    w.stroke_len = (uint8_t)len;
    w.freq = (int32_t)(CLAUSE_COST - 1) * (int32_t)len;
    w.pos_left = c->pos_def_l;
    w.pos_right = c->pos_def_r;
    return w;
}

/** getIndependentWords(input, false): the cached list of words with a unique right-hand POS. */
static size_t get_indep(wnn_conv_t *c, size_t start, size_t end, const wnn_word_t **list)
{
    wnn_list_t *e = &c->indep[start][end];
    if (!e->valid) {
        dics_for_indep(c);
        e->off = c->word_n;
        e->cnt = 0;
        e->valid = 1;
        uint8_t n = 0;
        if (search_range(c, NJ_CUR_OP_COMP, start, end)) {
            wnn_word_t w;
            bool eq = false;
            while (next_word(c, &w, &eq)) {
                if (!eq) {
                    continue;
                }
                bool found = false;
                for (uint8_t k = 0; k < n; k++) {
                    if (c->words[e->off + k].pos_right == w.pos_right) {
                        found = true;
                        break;
                    }
                }
                if (!found && !push_word(c, &w, &n)) {
                    break;
                }
                if (w.freq < 400) {
                    break;
                }
            }
        }
        const wnn_word_t auto_gen = plain_word(c, start, end - start);
        push_word(c, &auto_gen, &n);
        e->cnt = n;
    }
    *list = &c->words[e->off];
    return e->cnt;
}

/** getIndependentWords(input, true): every homophone, not cached, written to c->stems. */
static size_t get_indep_all(wnn_conv_t *c, size_t start, size_t end)
{
    dics_for_indep(c);
    size_t n = 0;
    if (search_range(c, NJ_CUR_OP_COMP, start, end)) {
        wnn_word_t w;
        bool eq = false;
        while (next_word(c, &w, &eq)) {
            if (!eq) {
                continue;
            }
            if (n >= WNN_MAX_LIST - 1) {
                break; /* more homophones than the candidate list can show anyway */
            }
            c->stems[n++] = w;
        }
    }
    c->stems[n++] = plain_word(c, start, end - start);
    return n;
}

/** getAncillaryPattern(input): the cached list for kana[start..end). */
static size_t get_fzk(wnn_conv_t *c, size_t start, size_t end, const wnn_word_t **list)
{
    *list = NULL;
    if (start >= end) {
        return 0;
    }
    if (!c->fzk[start][end].valid) {
        dics_for_fzk(c);
        for (size_t s = end; s-- > start;) {
            wnn_list_t *e = &c->fzk[s][end];
            if (e->valid) {
                continue;
            }
            e->off = c->word_n;
            e->cnt = 0;
            e->valid = 1;
            uint8_t n = 0;
            if (search_range(c, NJ_CUR_OP_COMP, s, end)) {
                wnn_word_t w;
                bool eq = false;
                while (next_word(c, &w, &eq)) {
                    (void)eq; /* the original adds every ancillary word a search returns */
                    if (!push_word(c, &w, &n)) {
                        break;
                    }
                }
            }
            /* Concatenate a sequence of ancillary words: a word over kana[s..mid) followed by the
             * list already built for kana[mid..end). The result reads and reads back as the kana. */
            for (size_t mid = end; mid-- > s + 1;) {
                const wnn_list_t *follow = &c->fzk[mid][end];
                if (!follow->valid || follow->cnt == 0) {
                    continue;
                }
                if (!search_range(c, NJ_CUR_OP_COMP, s, mid)) {
                    continue;
                }
                wnn_word_t w;
                bool eq = false;
                bool full = false;
                while (!full && next_word(c, &w, &eq)) {
                    (void)eq;
                    for (uint8_t j = 0; j < follow->cnt; j++) {
                        const wnn_word_t *f = &c->words[follow->off + j];
                        if (!connectible(c, w.pos_right, f->pos_left)) {
                            continue;
                        }
                        wnn_word_t cat = plain_word(c, s, end - s);
                        cat.freq = 0; /* the default WnnWord score of the original */
                        cat.pos_left = w.pos_left;
                        cat.pos_right = f->pos_right;
                        if (!push_word(c, &cat, &n)) {
                            full = true;
                            break;
                        }
                    }
                }
            }
            e->cnt = n;
        }
    }
    *list = &c->words[c->fzk[start][end].off];
    return c->fzk[start][end].cnt;
}

/* --- clauses --- */

static bool make_clause(wnn_conv_t *c, size_t start, size_t end, const wnn_word_t *stem,
                        const wnn_word_t *fzk, uint16_t terminal_left, wnn_word_t *out)
{
    if (fzk == NULL) {
        if (!connectible(c, stem->pos_right, terminal_left)) {
            return false;
        }
        *out = *stem;
    } else {
        if (!connectible(c, stem->pos_right, fzk->pos_left) ||
            !connectible(c, fzk->pos_right, terminal_left)) {
            return false;
        }
        *out = *stem;
        out->fzk_off = fzk->cand_off;
        out->fzk_len = fzk->cand_len;
        out->pos_right = fzk->pos_right;
    }
    out->stroke_start = (uint8_t)start;
    out->stroke_len = (uint8_t)(end - start);
    return true;
}

/** addClause(): keep the best clause (all == false) or insert by descending score. */
static bool add_clause(wnn_conv_t *c, size_t start, size_t end, const wnn_word_t *stem,
                       const wnn_word_t *fzk, uint16_t terminal_left, bool all, wnn_word_t *list,
                       size_t cap, size_t *count)
{
    wnn_word_t cl;
    if (cap == 0 || !make_clause(c, start, end, stem, fzk, terminal_left, &cl)) {
        return false;
    }
    if (*count == 0) {
        list[0] = cl;
        *count = 1;
        return true;
    }
    if (!all) {
        if (list[0].freq < cl.freq) {
            list[0] = cl;
            return true;
        }
        return false;
    }
    size_t idx = 0;
    while (idx < *count && list[idx].freq >= cl.freq) {
        idx++;
    }
    if (*count < cap) {
        memmove(&list[idx + 1], &list[idx], (*count - idx) * sizeof(list[0]));
        list[idx] = cl;
        (*count)++;
        return true;
    }
    /* The original list is unbounded; here the worst clause falls off the end. That is the caller's
     * candidate cap, not an internal limit, so it does not set the truncated flag. */
    if (idx + 1 < cap) {
        memmove(&list[idx + 1], &list[idx], (cap - idx - 1) * sizeof(list[0]));
        list[idx] = cl;
        return true;
    }
    return false;
}

/** singleClauseConvert(). */
static size_t single_clause(wnn_conv_t *c, size_t start, size_t end, uint16_t terminal_left,
                            bool all, wnn_word_t *list, size_t cap)
{
    size_t count = 0;
    const wnn_word_t *stems = NULL;
    size_t ns;

    if (all) {
        ns = get_indep_all(c, start, end);
        stems = c->stems;
    } else {
        ns = get_indep(c, start, end, &stems);
    }
    for (size_t i = 0; i < ns; i++) {
        add_clause(c, start, end, &stems[i], NULL, terminal_left, all, list, cap, &count);
    }

    int32_t max = CLAUSE_COST * 2;
    for (size_t split = 1; split < end - start; split++) {
        const wnn_word_t *fzks = NULL;
        const size_t nf = get_fzk(c, start + split, end, &fzks);
        if (nf == 0) {
            continue;
        }
        if (all) {
            ns = get_indep_all(c, start, start + split);
            stems = c->stems;
        } else {
            ns = get_indep(c, start, start + split, &stems);
        }
        for (size_t i = 0; i < ns; i++) {
            if (!all && stems[i].freq <= max) {
                continue;
            }
            for (size_t j = 0; j < nf; j++) {
                if (add_clause(c, start, end, &stems[i], &fzks[j], terminal_left, all, list, cap,
                               &count)) {
                    max = stems[i].freq;
                }
            }
        }
    }
    return count;
}

/* --- public interface --- */

size_t wnn_conv_sizeof(void)
{
    return sizeof(struct wnn_conv);
}

static bool check_dic(wnn_conv_t *c, const void *data, size_t len, NJ_UINT32 want_type, int slot)
{
    if (data == NULL || len <= NJ_DIC_COMMON_HEADER_SIZE) {
        return false;
    }
    NJ_DIC_HANDLE h = (NJ_DIC_HANDLE)(uintptr_t)data; /* the engine only reads a dictionary */
    if (njx_check_dic(&c->wnn, h, 0, (NJ_UINT32)len) < 0) {
        return false;
    }
    if (NJ_GET_DIC_TYPE(h) != want_type) {
        return false;
    }
    if (slot >= 0) {
        c->handle[slot] = h;
    } else {
        c->dicset.rHandle[NJ_MODE_TYPE_HENKAN] = h;
    }
    return true;
}

bool wnn_conv_init(void *mem, const wnn_dicts_t *d, wnn_conv_t **out)
{
    if (mem == NULL || d == NULL || out == NULL) {
        return false;
    }
    wnn_conv_t *c = (wnn_conv_t *)mem;
    memset(c, 0, sizeof(*c));
    if (njx_init(&c->wnn) < 0) {
        return false;
    }
    /* The rule dictionary first: njx_check_dic() of a rule dictionary needs no other state, and the
     * part-of-speech tags below come from it. */
    if (!check_dic(c, d->connect, d->connect_len, NJ_DIC_TYPE_RULE, -1) ||
        !check_dic(c, d->tankanji, d->tankanji_len, NJ_DIC_TYPE_TANKANJI, DIC_TANKANJI - DIC_FIRST) ||
        !check_dic(c, d->jiritsu, d->jiritsu_len, NJ_DIC_TYPE_JIRITSU, DIC_JIRITSU - DIC_FIRST) ||
        !check_dic(c, d->fzk, d->fzk_len, NJ_DIC_TYPE_FZK, DIC_FZK - DIC_FIRST)) {
        return false;
    }
    NJ_DIC_HANDLE rule = c->dicset.rHandle[NJ_MODE_TYPE_HENKAN];
    njd_r_get_count(rule, &c->lcount, &c->rcount);
    if (c->lcount == 0 || c->rcount == 0) {
        return false;
    }
    c->pos_def_l = (uint16_t)njd_r_get_hinsi(rule, NJ_HINSI_MEISI_F);
    c->pos_def_r = (uint16_t)njd_r_get_hinsi(rule, NJ_HINSI_MEISI_B);
    c->pos_eoc1_l = (uint16_t)njd_r_get_hinsi(rule, NJ_HINSI_V1_F);
    c->pos_eoc2_l = (uint16_t)njd_r_get_hinsi(rule, NJ_HINSI_V2_F);
    c->pos_eoc3_l = (uint16_t)njd_r_get_hinsi(rule, NJ_HINSI_V3_F);
    if (c->pos_def_l == 0 || c->pos_def_r == 0 || c->pos_eoc1_l == 0 || c->pos_eoc2_l == 0 ||
        c->pos_eoc3_l == 0) {
        return false;
    }
    *out = c;
    return true;
}

static void reset_caches(wnn_conv_t *c)
{
    memset(c->indep, 0, sizeof(c->indep));
    memset(c->fzk, 0, sizeof(c->fzk));
    c->word_n = 0;
    c->str_n = WNN_MAX_KANA; /* str[0..WNN_MAX_KANA) is the reading itself */
    c->truncated = false;
}

bool wnn_conv_set_input(wnn_conv_t *c, const uint16_t *kana, size_t len)
{
    if (c == NULL || kana == NULL || len > WNN_MAX_KANA) {
        return false;
    }
    for (size_t i = 0; i < len; i++) {
        nj_put(&c->kana[i], kana[i]);
        c->str[i] = kana[i];
    }
    c->kana[len] = NJ_CHAR_NUL;
    for (size_t i = len; i < WNN_MAX_KANA; i++) {
        c->str[i] = 0;
    }
    c->kana_len = (uint8_t)len;
    reset_caches(c);
    return true;
}

size_t wnn_conv_sentence(wnn_conv_t *c, size_t base, wnn_word_t *out, size_t cap)
{
    if (c == NULL || out == NULL || base >= c->kana_len) {
        return 0;
    }
    reset_caches(c);
    const size_t len = (size_t)c->kana_len - base;
    for (size_t i = 0; i < len; i++) {
        c->dp[i].set = false;
    }
    for (size_t start = 0; start < len; start++) {
        if (start != 0 && !c->dp[start - 1].set) {
            continue;
        }
        size_t end = len;
        if (end > start + MAX_CLAUSE_KANA) {
            end = start + MAX_CLAUSE_KANA;
        }
        for (; end > start; end--) {
            const size_t idx = end - 1;
            const int32_t prev = start != 0 ? c->dp[start - 1].freq : 0;
            if (c->dp[idx].set && c->dp[idx].freq > prev + CLAUSE_COST + FREQ_LEARN) {
                break; /* no way for a better sequence to start here */
            }
            wnn_word_t best;
            const uint16_t terminal = (end == len) ? c->pos_eoc1_l : c->pos_eoc3_l;
            if (single_clause(c, base + start, base + end, terminal, false, &best, 1) == 0) {
                best = plain_word(c, base + start, end - start);
            }
            const int32_t freq = prev + best.freq + CLAUSE_COST;
            if (!c->dp[idx].set || c->dp[idx].freq < freq) {
                c->dp[idx].set = true;
                c->dp[idx].freq = freq;
                c->dp[idx].start = (uint8_t)start;
                c->dp[idx].clause = best;
            }
        }
    }
    if (!c->dp[len - 1].set) {
        return 0;
    }
    /* Walk the back pointers, then put the clauses in reading order. */
    size_t n = 0;
    size_t idx = len - 1;
    for (;;) {
        if (n < cap) {
            out[n] = c->dp[idx].clause;
        }
        n++;
        const size_t s = c->dp[idx].start;
        if (s == 0) {
            break;
        }
        idx = s - 1;
    }
    if (n > cap) {
        c->truncated = true;
        return 0;
    }
    for (size_t i = 0, j = n - 1; i < j; i++, j--) {
        const wnn_word_t t = out[i];
        out[i] = out[j];
        out[j] = t;
    }
    return n;
}

size_t wnn_conv_clause_all(wnn_conv_t *c, size_t start, size_t len, wnn_word_t *out, size_t cap)
{
    if (c == NULL || out == NULL || len == 0 || start + len > c->kana_len) {
        return 0;
    }
    return single_clause(c, start, start + len, c->pos_eoc2_l, true, out, cap);
}

size_t wnn_conv_text(const wnn_conv_t *c, const wnn_word_t *w, uint16_t *out)
{
    size_t n = 0;
    for (size_t i = 0; i < w->cand_len; i++) {
        out[n++] = c->str[w->cand_off + i];
    }
    for (size_t i = 0; i < w->fzk_len; i++) {
        out[n++] = c->str[w->fzk_off + i];
    }
    return n;
}

size_t wnn_conv_katakana(const wnn_conv_t *c, size_t start, size_t len, uint16_t *out)
{
    NJ_CHAR hira[WNN_MAX_KANA + NJ_TERM_LEN];
    NJ_CHAR kata[WNN_MAX_KANA + NJ_TERM_LEN];
    if (len == 0 || start + len > c->kana_len) {
        return 0;
    }
    memcpy(hira, &c->kana[start], len * sizeof(NJ_CHAR));
    hira[len] = NJ_CHAR_NUL;
    const NJ_INT16 n = nje_convert_hira_to_kata(hira, kata, (NJ_UINT16)len);
    if (n <= 0) {
        return 0;
    }
    for (size_t i = 0; i < (size_t)n; i++) {
        out[i] = nj_get(&kata[i]);
    }
    return (size_t)n;
}

bool wnn_conv_truncated(const wnn_conv_t *c)
{
    return c->truncated;
}
