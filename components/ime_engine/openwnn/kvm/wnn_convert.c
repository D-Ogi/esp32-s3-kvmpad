/*
 * C translation by KVMpad of src/jp/co/omronsoft/openwnn/JAJP/OpenWnnClauseConverterJAJP.java,
 * the dictionary part of src/jp/co/omronsoft/openwnn/OpenWnnDictionaryImpl.java and
 * libs/libwnnDictionary/OpenWnnDictionaryImplJni.c of AOSP
 * platform/packages/inputmethods/OpenWnn at commit 5067ec8ec5a80ab12218c961f9b083fbccc71b93
 * (see THIRD_PARTY_NOTICES.md). The conversion rules, scores and search order are the original
 * ones; what differs, and why:
 *
 *  - No user and no learning dictionary. The Java original mixes in SQLite-backed user and learning
 *    dictionaries (FREQ_USER / FREQ_LEARN entries, njx_select() feedback). KVMpad stores nothing the
 *    user typed (AGENTS.md section 4), so only the three fixed dictionaries of WnnJpnDic.c are set
 *    and njx_select() is never called. FREQ_LEARN stays in the branch-cutting rule below, which is
 *    where the original uses it as a constant.
 *  - No approximate (flick) patterns: the charset stays empty, as clearApproxPattern() leaves it.
 *  - Fixed memory. The original keeps unbounded HashMap caches of word lists keyed by substrings and
 *    an ArrayList per clause; here every list is a range of a fixed word arena indexed by the
 *    (start, end) kana positions of the reading, and the consecutive-clause search keeps one best
 *    sub-sentence per end position with a back pointer instead of a WnnSentence object per cell. A
 *    list that does not fit is kept short and wnn_conv_truncated() reports it: a conversion may then
 *    miss a candidate, but nothing becomes unsafe.
 *  - A word's reading is the (start, length) range of the conversion input instead of a string copy,
 *    and a clause keeps its stem and ancillary text separately instead of a concatenated string.
 *  - The dictionary set is only reconfigured when it actually changes, which keeps the engine's own
 *    search cache warm; the original clears it before every batch of searches.
 *  - getStroke() / getCandidate() failures skip the word and the search goes on, instead of handing
 *    the caller a word with null strings.
 *  - The branch of singleClauseConvert() that runs when the stem list is empty is dropped: it is
 *    unreachable, because addAutoGeneratedCandidates() always appends one word.
 */
