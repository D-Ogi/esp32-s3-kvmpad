typedef struct {
    const uint8_t *data;
    size_t size;
} motion_record_t;

static const motion_record_t records[2][2] = {
    {{vga_1, sizeof(vga_1)}, {vga_2, sizeof(vga_2)}},
    {{native_1, sizeof(native_1)}, {native_2, sizeof(native_2)}},
};

size_t usb_motion_jpeg_size(bool native, unsigned position)
{
    if (position < 1 || position > 2) return 0;
    return records[native][position - 1].size - 16;
}

void usb_motion_feed(bool native, unsigned position, void (*feed)(const uint8_t *, size_t))
{
    if (!feed || position < 1 || position > 2) return;
    motion_record_t record = records[native][position - 1];
    for (size_t offset = 0; offset < record.size; offset += 64) {
        size_t left = record.size - offset;
        feed(record.data + offset, left < 64 ? left : 64);
    }
}
