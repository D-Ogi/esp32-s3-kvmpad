"""Generate two baseline JPEGs and independent native RGB565 framebuffer checksums."""
import argparse
from io import BytesIO
from pathlib import Path
import struct
import zlib

from PIL import Image


def picture(phase):
    colors = [(76, 85, 255), (149, 43, 21), (29, 255, 107), (255, 128, 128)]
    rgb565 = [0xf800, 0x07e0, 0x001f, 0xffff]
    im = Image.new("YCbCr", (512, 512))
    raw = bytearray()
    for half in range(2):
        row = bytearray()
        for side in range(2):
            index = (2 * half + side + phase) % 4
            x, y = 256 * side, 256 * half
            im.paste(colors[index], (x, y, x + 256, y + 256))
            row.extend(struct.pack("<H", rgb565[index]) * 256)
        raw.extend(row * 256)
    jpeg = BytesIO()
    im.save(jpeg, format="JPEG", quality=100, subsampling=2, progressive=False, optimize=True)
    return jpeg.getvalue(), raw


def generate(out):
    text = [line.replace("# ", "// ", 1) for line in Path(__file__).read_text().splitlines()[:3]]
    text += ["#pragma once", "// Generated by test/live_view/generate_synthetic_jpeg.py", "#include <stdint.h>", ""]
    checksums = []
    for phase in range(2):
        unit, pixels = picture(phase)
        checksums.append(zlib.crc32(pixels))
        text.append(f"static const uint8_t synthetic_jpeg_{phase}[] = {{")
        for i in range(0, len(unit), 16):
            text.append("    " + ", ".join(f"0x{v:02x}" for v in unit[i:i + 16]) + ",")
        text.append("};")
    text.append("static const uint32_t synthetic_jpeg_crc[] = {" + ", ".join(f"0x{x:08x}" for x in checksums) + "};")
    out.write_text("\n".join(text) + "\n", encoding="ascii")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("out", type=Path)
    generate(parser.parse_args().out)
