"""Generate the two original, offline H.264 checkerboards for the opt-in device diagnostic."""
import argparse
from pathlib import Path
import re
import subprocess
import zlib

import numpy as np


def picture(phase):
    y, x = np.indices((512, 512))
    luma = np.where((x // 128 + y // 128 + phase) & 1, 208, 48).astype(np.uint8)
    raw = luma.tobytes() + bytes([128]) * (512 * 512 // 2)
    unit = subprocess.check_output([
        "ffmpeg", "-v", "error", "-f", "rawvideo", "-pix_fmt", "yuv420p", "-s", "512x512", "-i", "-",
        "-frames:v", "1", "-c:v", "libx264", "-pix_fmt", "yuv420p", "-threads", "1", "-profile:v",
        "baseline", "-x264-params", "keyint=1:ref=1:slices=1:aud=0", "-qp", "24", "-f", "h264", "-"],
        input=raw)
    units = [part for part in re.split(b"\x00\x00+\x01", unit) if part and part[0] & 31 in (7, 8, 5)]
    unit = b"".join(b"\x00\x00\x00\x01" + part for part in units)
    decoded = subprocess.check_output(["ffmpeg", "-v", "error", "-f", "h264", "-i", "-", "-frames:v", "1",
                                       "-pix_fmt", "yuv420p", "-f", "rawvideo", "-"], input=unit)
    assert decoded[512 * 512:] == bytes([128]) * (512 * 512 // 2)
    yy = np.frombuffer(decoded, np.uint8, 512 * 512).astype(np.int32)
    v = np.clip(((yy - 16) * 298 + 128) // 256, 0, 255).astype(np.uint16)
    rgb = ((v >> 3) << 11) | ((v >> 2) << 5) | (v >> 3)
    return unit, zlib.crc32(rgb.astype("<u2").tobytes())


def generate(out):
    text = [line.replace("# ", "// ", 1) for line in Path(__file__).read_text().splitlines()[:3]]
    text += ["#pragma once", "// Generated by test/live_view/generate_synthetic_idr.py", "#include <stdint.h>", ""]
    checksums = []
    for phase in range(2):
        unit, crc = picture(phase)
        checksums.append(crc)
        text.append(f"static const uint8_t synthetic_idr_{phase}[] = {{")
        for i in range(0, len(unit), 16):
            text.append("    " + ", ".join(f"0x{v:02x}" for v in unit[i:i + 16]) + ",")
        text.append("};")
    text.append("static const uint32_t synthetic_idr_crc[] = {" + ", ".join(f"0x{x:08x}" for x in checksums) + "};")
    out.write_text("\n".join(text) + "\n", encoding="ascii")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("out", type=Path)
    generate(parser.parse_args().out)
